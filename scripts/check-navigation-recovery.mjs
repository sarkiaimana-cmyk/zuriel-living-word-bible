import fs from "node:fs";
import assert from "node:assert/strict";
const html=fs.readFileSync("index.html","utf8");
const recovery=fs.readFileSync("zuriel-navigation-recovery.js","utf8");
const home=fs.readFileSync("zuriel-home.js","utf8");
const settings=fs.readFileSync("zuriel-settings.js","utf8");
assert.match(html,/zuriel-navigation-recovery\\.js/,"Recovery safeguards are wired into HTML");
assert.match(html,/<nav id="zurielBottomNavigation"/,"Navigation is present in initial HTML before app modules execute");
for(const id of ["home","read","study","library","kingdom","personal","settings"])assert.match(html,new RegExp('data-section="' + id + '"'),"Initial navigation includes "+id);
assert.match(recovery,/getElementById\\("zurielBottomNavigation"\\)/);
assert.match(recovery,/if\\(!nav\\|\\|!main\\)return/,"Recovery must wait for the one native navigation element");
assert.doesNotMatch(recovery,/createElement\\("nav"\\)/,"Recovery must never create a duplicate navigation element");
for(const id of ["home","read","study","library","kingdom","personal"])assert.ok(recovery.includes('"'+id+'"'),"Recovery must safeguard "+id);
assert.match(recovery,/position:fixed!important/,"Nav must be fixed to viewport");
assert.match(recovery,/visibility:visible!important/,"Recovery explicitly restores visibility");
assert.match(recovery,/display:grid!important/,"Recovery overrides styles that hide navigation");
assert.match(recovery,/pointer-events:auto!important/,"Recovered navigation remains touch-interactive");
assert.match(recovery,/nav\\.hidden=false/,"Recovery clears the hidden property");
assert.match(home,/getElementById\\("zurielBottomNavigation"\\) \\|\\| document\\.createElement\\("nav"\\)/,"Home module reuses the one initial navigation element");
assert.match(home,/zurielHomeBound !== "1"/,"Primary navigation actions are bound exactly once");
assert.match(home,/window\\.ZurielHomeNavigate\\s*=\\s*navigate/,"Existing navigation API is exposed");
assert.match(settings,/zurielSettingsBound !== "1"/,"Settings action is bound exactly once");
assert.match(settings,/new MutationObserver/,"Settings initialization retries until navigation exists");
assert.match(settings,/retrySettingsInit\\.disconnect\\(\\)/,"Settings retry observer disconnects after initialization");
assert.match(settings,/if \\(initialized\\) return true/,"Settings initialization is idempotent");
assert.match(recovery,/new MutationObserver/,"Recovery waits for delayed nav creation");
assert.match(recovery,/repairObserver\\.observe\\(document\\.documentElement/,"Recovery watches DOM for delayed navigation");
assert.match(recovery,/repairObserver\\.disconnect\\(\\)/,"Recovery observer stops after successful repair");
console.log("Initial seven-item navigation, single-owner handlers, and delayed recovery passed.");
