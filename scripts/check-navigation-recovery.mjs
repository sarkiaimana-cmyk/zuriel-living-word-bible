import fs from "node:fs";
import assert from "node:assert/strict";
const html=fs.readFileSync("index.html","utf8");
const recovery=fs.readFileSync("zuriel-navigation-recovery.js","utf8");
const home=fs.readFileSync("zuriel-home.js","utf8");
const settings=fs.readFileSync("zuriel-settings.js","utf8");
assert.ok(html.includes("zuriel-navigation-recovery.js"),"Recovery safeguards are wired into HTML");
assert.ok(html.includes('<nav id="zurielBottomNavigation"'),"Navigation is present in initial HTML before app modules execute");
for(const id of ["home","read","study","library","kingdom","personal","settings"])assert.ok(html.includes('data-section="'+id+'"'),"Initial navigation includes "+id);
assert.ok(recovery.includes('getElementById("zurielBottomNavigation")'));
assert.ok(recovery.includes("if(!nav||!main)return"),"Recovery must wait for the one native navigation element");
assert.ok(!recovery.includes('createElement("nav")'),"Recovery must never create a duplicate navigation element");
for(const id of ["home","read","study","library","kingdom","personal"])assert.ok(recovery.includes('"'+id+'"'),"Recovery must safeguard "+id);
assert.ok(recovery.includes("position:fixed!important"),"Nav must be fixed to viewport");
assert.ok(recovery.includes("visibility:visible!important"),"Recovery explicitly restores visibility");
assert.ok(recovery.includes("display:grid!important"),"Recovery overrides styles that hide navigation");
assert.ok(recovery.includes("pointer-events:auto!important"),"Recovered navigation remains touch-interactive");
assert.ok(recovery.includes("nav.hidden=false"),"Recovery clears the hidden property");
assert.ok(home.includes('getElementById("zurielBottomNavigation") || document.createElement("nav")'),"Home module reuses the one initial navigation element");
assert.ok(home.includes('button.dataset.zurielHomeBound !== "1"'),"Primary navigation actions are bound exactly once");
assert.ok(home.includes("window.ZurielHomeNavigate = navigate"),"Existing navigation API is exposed");
assert.ok(settings.includes('settingsButton.dataset.zurielSettingsBound !== "1"'),"Settings action is bound exactly once");
assert.ok(settings.includes("new MutationObserver"),"Settings initialization retries until navigation exists");
assert.ok(settings.includes("retrySettingsInit.disconnect()"),"Settings retry observer disconnects after initialization");
assert.ok(settings.includes("if (initialized) return true"),"Settings initialization is idempotent");
assert.ok(recovery.includes("new MutationObserver"),"Recovery waits for delayed nav creation");
assert.ok(recovery.includes("repairObserver.observe(document.documentElement"),"Recovery watches DOM for delayed navigation");
assert.ok(recovery.includes("repairObserver.disconnect()"),"Recovery observer stops after successful repair");
console.log("Initial seven-item navigation, single-owner handlers, and delayed recovery passed.");
